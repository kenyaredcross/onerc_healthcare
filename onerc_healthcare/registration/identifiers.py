"""Patient identifiers: normalisation, validation, duplicate prevention (FR-1 to FR-3, C-6, NFR-10).

Uniqueness is enforced twice (SDD 4.3, FR-2):
- `validate_patient` gives a friendly error naming the patient that already holds the identifier;
- a DB unique index on `tabPatient Identifier` (identifier_type, unique_key), created in
  `setup.install`, holds even when two receptionists save the same identifier at the same moment.
  `unique_key` is the normalised value for types marked Is Unique and NULL otherwise (NULLs never
  collide), so shared identifiers such as household ration cards are allowed.

Facility-generated identifiers are created only by the system (walk-in registration) and can never be
typed, edited or removed by hand: a typed value could otherwise collide with a future generated number.
"""

import re

import frappe
from frappe import _
from frappe.utils import get_link_to_form, today

from onerc_healthcare.constants import (
	IDENTIFIER_FACILITY,
	PATIENT_IDENTIFIER_DOCTYPE,
	PATIENT_IDENTIFIER_TYPE_DOCTYPE,
	PATIENT_IDENTIFIERS_FIELD,
	PATIENT_WALK_IN_FIELD,
	PRIMARY_IDENTIFIER_TYPES,
)
from onerc_healthcare.registration.names import (
	FIRST_NAME_KEY_FIELD,
	LAST_NAME_KEY_FIELD,
	name_key,
	normalise_name,
)

# Patient field names owned by A1 (constants.py holds only the shared contract ones).
MERGED_INTO_FIELD = "krcs_merged_into"
POPULATION_GROUP_FIELD = "krcs_population_group"
RESIDENCE_FIELD = "krcs_residence"
OVERRIDE_REASON_FIELD = "krcs_duplicate_override_reason"
SEARCH_FIELD = "krcs_identifier_search"
REGISTRATION_FACILITY_FIELD = "krcs_registration_facility"
MERGE_LOG_FIELD = "krcs_merge_log"

UNIQUE_CONSTRAINT = "krcs_unique_identifier"
VERIFIED = "Verified"
WALK_IN_VERIFICATION_SOURCE = "Generated by the system at walk-in registration"

_NON_ALNUM = re.compile(r"[\W_]+", re.UNICODE)


class DuplicateIdentifierError(frappe.ValidationError):
	pass


class PossibleDuplicatePatientError(frappe.ValidationError):
	pass


class FacilityIdentifierError(frappe.ValidationError):
	pass


def clean_value(value: str | None) -> str:
	"""Display form: trimmed, inner whitespace collapsed, upper case."""
	return " ".join((value or "").split()).upper()


def normalise(value: str | None) -> str:
	"""Matching form: upper case without whitespace or punctuation (SDD 4.3). `kak-12 345` -> `KAK12345`."""
	return _NON_ALNUM.sub("", clean_value(value))


def get_identifier_types() -> dict[str, frappe._dict]:
	rows = frappe.get_all(
		PATIENT_IDENTIFIER_TYPE_DOCTYPE,
		fields=[
			"name",
			"is_primary",
			"is_unique",
			"population_group",
			"enabled",
			"value_pattern",
			"pattern_hint",
		],
	)
	return {r.name: r for r in rows}


def is_unique_type(identifier_type: str) -> bool:
	"""Whether each value of this type may belong to one patient only (M9: ration cards are shared)."""
	value = frappe.db.get_value(PATIENT_IDENTIFIER_TYPE_DOCTYPE, identifier_type, "is_unique")
	return value is None or bool(value)


def primary_type_names() -> list[str]:
	names = [t.name for t in get_identifier_types().values() if t.is_primary and t.enabled]
	return names or list(PRIMARY_IDENTIFIER_TYPES)


def find_identifier_owner(
	identifier_type: str, value: str, exclude: str | None = None, unique_only: bool = True
) -> str | None:
	"""Name of the Patient that holds this identifier (any spelling of it), other than `exclude`.

	With `unique_only` (the default), shared identifier types (Is Unique off) never have an "owner"."""
	normalised = normalise(value)
	if not identifier_type or not normalised:
		return None
	if unique_only and not is_unique_type(identifier_type):
		return None
	filters = {
		"identifier_type": identifier_type,
		"normalised_value": normalised,
		"parenttype": "Patient",
		"parentfield": PATIENT_IDENTIFIERS_FIELD,
	}
	if exclude:
		filters["parent"] = ["!=", exclude]
	owners = frappe.get_all(PATIENT_IDENTIFIER_DOCTYPE, filters=filters, pluck="parent", limit=1)
	return owners[0] if owners else None


def describe_patient(patient: str) -> str:
	"""`<link> (Name)`, plus where it was merged into, for error messages."""
	name, merged_into = frappe.db.get_value("Patient", patient, ["patient_name", MERGED_INTO_FIELD]) or (
		"",
		None,
	)
	text = f"{get_link_to_form('Patient', patient)} ({frappe.utils.escape_html(name or '')})"
	if merged_into:
		text += " " + _("which was merged into {0}").format(get_link_to_form("Patient", merged_into))
	return text


def duplicate_message(identifier_type: str, value: str, owner: str) -> str:
	return _(
		"{0} {1} is already registered to patient {2}. Open that record instead of registering the "
		"patient again (FR-2)."
	).format(
		frappe.bold(identifier_type), frappe.bold(frappe.utils.escape_html(value)), describe_patient(owner)
	)


def is_new_row(row) -> bool:
	return (
		bool(row.get("__islocal"))
		or not row.name
		or not frappe.db.exists(PATIENT_IDENTIFIER_DOCTYPE, row.name)
	)


def is_merging(doc) -> bool:
	return bool(doc.flags.krcs_merging or doc.get(MERGED_INTO_FIELD))


def validate_patient(doc) -> None:
	"""Patient `validate`: identifier rules, population group default, walk-in identifier, search index."""
	_guard_merged(doc)
	_set_registration_facility(doc)
	set_name_keys(doc)
	_guard_facility_rows(doc)
	_validate_rows(doc)
	if doc.get(PATIENT_WALK_IN_FIELD) and not is_merging(doc):
		ensure_walk_in_identifier(doc)
	_validate_primary_present(doc)
	_set_population_group(doc)
	set_search_index(doc)
	if doc.is_new() and not is_merging(doc):
		check_strong_duplicate(doc)


def set_name_keys(doc) -> None:
	doc.set(FIRST_NAME_KEY_FIELD, name_key(doc.first_name))
	doc.set(LAST_NAME_KEY_FIELD, name_key(doc.last_name))


def find_strong_duplicates(doc) -> list[str]:
	"""Unmerged patients with the same normalised first and last name, date of birth and sex."""
	if not (doc.first_name and doc.dob and doc.sex):
		return []
	candidates = frappe.get_all(
		"Patient",
		filters={
			FIRST_NAME_KEY_FIELD: name_key(doc.first_name),
			LAST_NAME_KEY_FIELD: name_key(doc.last_name) or ["is", "not set"],
			"dob": doc.dob,
			"sex": doc.sex,
			MERGED_INTO_FIELD: ["is", "not set"],
			"name": ["!=", doc.name or ""],
		},
		fields=["name", "first_name", "last_name"],
		limit=50,
	)
	first, last = normalise_name(doc.first_name), normalise_name(doc.last_name)
	return [
		c.name
		for c in candidates
		if normalise_name(c.first_name) == first and normalise_name(c.last_name) == last
	]


def check_strong_duplicate(doc) -> None:
	"""L2: a new patient identical in name, DOB and sex to an existing one needs a recorded reason (FR-2)."""
	if (doc.get(OVERRIDE_REASON_FIELD) or "").strip():
		return
	matches = find_strong_duplicates(doc)
	if matches:
		frappe.throw(
			_(
				"A patient with the same name, date of birth and sex is already registered: {0}. Open that "
				"record, or, if this is a different person, record the reason in {1} (FR-2)."
			).format(
				", ".join(describe_patient(m) for m in matches),
				frappe.bold(_("Reason for Registering Despite Possible Matches")),
			),
			exc=PossibleDuplicatePatientError,
			title=_("Possible Duplicate Patient"),
		)


def _guard_facility_rows(doc) -> None:
	"""H1: Facility-generated identifiers are system-assigned; they cannot be typed, changed or removed."""
	rows = doc.get(PATIENT_IDENTIFIERS_FIELD) or []
	stored = {}
	if not doc.is_new():
		stored = {
			r.name: r
			for r in frappe.get_all(
				PATIENT_IDENTIFIER_DOCTYPE,
				filters={
					"parent": doc.name,
					"parenttype": "Patient",
					"parentfield": PATIENT_IDENTIFIERS_FIELD,
				},
				fields=["name", "identifier_type", "identifier_value", "normalised_value"],
			)
		}
	for row in rows:
		before = stored.get(row.name) if row.name else None
		if row.identifier_type != IDENTIFIER_FACILITY and not (
			before and before.identifier_type == IDENTIFIER_FACILITY
		):
			continue
		if row.flags.krcs_system_generated:
			continue
		if not before:
			frappe.throw(
				_(
					"Identifiers row {0}: {1} identifiers are assigned by the system when {2} is ticked and "
					"cannot be entered by hand."
				).format(
					row.idx, frappe.bold(IDENTIFIER_FACILITY), frappe.bold(_("Walk-in (no identifier)"))
				),
				exc=FacilityIdentifierError,
				title=_("Not Allowed"),
			)
		if row.identifier_type != before.identifier_type or normalise(row.identifier_value) != (
			before.normalised_value or normalise(before.identifier_value)
		):
			frappe.throw(
				_("Identifiers row {0}: the {1} identifier {2} cannot be changed.").format(
					row.idx, IDENTIFIER_FACILITY, frappe.bold(before.identifier_value)
				),
				exc=FacilityIdentifierError,
				title=_("Not Allowed"),
			)
	kept = {r.name for r in rows}
	for name, before in stored.items():
		if before.identifier_type == IDENTIFIER_FACILITY and name not in kept:
			frappe.throw(
				_("The {0} identifier {1} cannot be removed.").format(
					IDENTIFIER_FACILITY, frappe.bold(before.identifier_value)
				),
				exc=FacilityIdentifierError,
				title=_("Not Allowed"),
			)


def _guard_merged(doc) -> None:
	"""A merged record is frozen; `krcs_merged_into` is set only by the merge routine (SDD 4.3)."""
	if doc.flags.krcs_merging:
		return
	before = None if doc.is_new() else frappe.db.get_value("Patient", doc.name, MERGED_INTO_FIELD)
	if before:
		frappe.throw(
			_("Patient {0} was merged into {1} and can no longer be edited. Edit {1} instead.").format(
				doc.name, get_link_to_form("Patient", before)
			),
			title=_("Merged Patient"),
		)
	if doc.get(MERGED_INTO_FIELD):
		frappe.throw(
			_("{0} is set only by the Merge Patients action.").format(_("Merged Into")),
			title=_("Not Allowed"),
		)


def _set_registration_facility(doc) -> None:
	from onerc_healthcare.registration.walk_in import get_default_registration_facility, validate_facility

	if doc.get(REGISTRATION_FACILITY_FIELD):
		if doc.is_new() or doc.has_value_changed(REGISTRATION_FACILITY_FIELD):
			validate_facility(doc.get(REGISTRATION_FACILITY_FIELD))
	elif doc.is_new():
		doc.set(REGISTRATION_FACILITY_FIELD, get_default_registration_facility())


def _validate_rows(doc) -> None:
	types = get_identifier_types()
	seen: dict[str, int] = {}
	for row in doc.get(PATIENT_IDENTIFIERS_FIELD) or []:
		label = _("Identifiers row {0}").format(row.idx)
		if not row.identifier_type:
			frappe.throw(_("{0}: Identifier Type is required.").format(label), title=_("Missing Value"))
		itype = types.get(row.identifier_type)
		if not itype:
			frappe.throw(
				_("{0}: {1} is not a known identifier type.").format(label, frappe.bold(row.identifier_type))
			)
		new_row = is_new_row(row)
		if not itype.enabled and new_row:
			frappe.throw(
				_("{0}: identifier type {1} is disabled and cannot be added.").format(
					label, frappe.bold(row.identifier_type)
				)
			)

		value = clean_value(row.identifier_value)
		if not value:
			frappe.throw(
				_("{0}: enter the {1} value.").format(label, frappe.bold(row.identifier_type)),
				title=_("Missing Value"),
			)
		normalised = normalise(value)
		if not normalised:
			frappe.throw(
				_("{0}: {1} {2} has no letters or digits.").format(
					label, row.identifier_type, frappe.bold(frappe.utils.escape_html(value))
				),
				title=_("Invalid Identifier"),
			)
		if itype.value_pattern and not re.fullmatch(itype.value_pattern, value):
			hint = _(" Expected format: {0}.").format(itype.pattern_hint) if itype.pattern_hint else ""
			frappe.throw(
				_("{0}: {1} {2} does not have the expected format.{3}").format(
					label, row.identifier_type, frappe.bold(frappe.utils.escape_html(value)), hint
				),
				title=_("Invalid Identifier"),
			)

		if row.identifier_type in seen:
			frappe.throw(
				_("{0} is entered twice (rows {1} and {2}). A patient can hold only one {0}.").format(
					frappe.bold(row.identifier_type), seen[row.identifier_type], row.idx
				),
				title=_("Duplicate Identifier Type"),
			)
		seen[row.identifier_type] = row.idx

		row.identifier_value = value
		row.normalised_value = normalised
		row.unique_key = normalised if is_unique(itype) else None
		row.is_primary = itype.is_primary
		_validate_verification(row, label)

		owner = (
			find_identifier_owner(row.identifier_type, normalised, exclude=doc.name)
			if row.unique_key
			else None
		)
		if owner:
			frappe.throw(
				duplicate_message(row.identifier_type, value, owner),
				exc=DuplicateIdentifierError,
				title=_("Identifier Already Registered"),
			)


def is_unique(itype) -> bool:
	return itype.is_unique is None or bool(itype.is_unique)


def _validate_verification(row, label: str) -> None:
	row.verification_status = row.verification_status or "Unverified"
	if row.verification_status == VERIFIED:
		if not row.verification_source:
			frappe.throw(
				_("{0}: enter the Verification Source for the verified {1}.").format(
					label, row.identifier_type
				),
				title=_("Missing Value"),
			)
		row.verified_on = row.verified_on or today()
	if row.verified_on and str(row.verified_on) > today():
		frappe.throw(_("{0}: Verified On cannot be in the future.").format(label), title=_("Invalid Date"))


def ensure_walk_in_identifier(doc) -> None:
	"""Give a walk-in Patient its facility-generated identifier if it has none yet (FR-3)."""
	from onerc_healthcare.registration.walk_in import generate_walk_in_identifier

	rows = doc.get(PATIENT_IDENTIFIERS_FIELD) or []
	if any(r.identifier_type == IDENTIFIER_FACILITY for r in rows):
		return
	facility = doc.get(REGISTRATION_FACILITY_FIELD)
	if not facility:
		frappe.throw(
			_("Set the Registration Facility so a walk-in identifier can be generated."),
			title=_("Missing Value"),
		)
	value = generate_walk_in_identifier(facility)
	row = doc.append(
		PATIENT_IDENTIFIERS_FIELD,
		{
			"identifier_type": IDENTIFIER_FACILITY,
			"identifier_value": value,
			"normalised_value": normalise(value),
			"unique_key": normalise(value),
			"is_primary": 0,
			"verification_status": VERIFIED,
			"verified_on": today(),
			"verification_source": WALK_IN_VERIFICATION_SOURCE,
		},
	)
	row.flags.krcs_system_generated = True


def _validate_primary_present(doc) -> None:
	if doc.get(PATIENT_WALK_IN_FIELD) or doc.get(MERGED_INTO_FIELD):
		return
	primary = set(primary_type_names())
	if any(r.identifier_type in primary for r in doc.get(PATIENT_IDENTIFIERS_FIELD) or []):
		return
	frappe.throw(
		_(
			"Add at least one primary identifier ({0}) in the Identifiers table. If the patient has none, "
			"tick {1} and a facility identifier will be generated (FR-1, FR-3)."
		).format(", ".join(primary_type_names()), frappe.bold(_("Walk-in (no identifier)"))),
		title=_("Primary Identifier Required"),
	)


def _set_population_group(doc) -> None:
	if doc.get(POPULATION_GROUP_FIELD):
		return
	types = get_identifier_types()
	rows = sorted(doc.get(PATIENT_IDENTIFIERS_FIELD) or [], key=lambda r: (not r.is_primary, r.idx))
	for row in rows:
		itype = types.get(row.identifier_type)
		if itype and itype.population_group:
			doc.set(POPULATION_GROUP_FIELD, itype.population_group)
			return


def set_search_index(doc) -> None:
	"""Hidden text holding every identifier as typed and normalised, so Patient search finds it."""
	terms: list[str] = []
	for row in doc.get(PATIENT_IDENTIFIERS_FIELD) or []:
		for term in (
			clean_value(row.identifier_value),
			row.normalised_value or normalise(row.identifier_value),
		):
			if term and term not in terms:
				terms.append(term)
	doc.set(SEARCH_FIELD, " ".join(terms))


def display_identifier(patient: str) -> str | None:
	"""`Type: Value` of the first primary identifier, else the first identifier (as Patient Visit shows it)."""
	rows = frappe.get_all(
		PATIENT_IDENTIFIER_DOCTYPE,
		filters={"parent": patient, "parenttype": "Patient", "parentfield": PATIENT_IDENTIFIERS_FIELD},
		fields=["identifier_type", "identifier_value", "is_primary"],
		order_by="idx asc",
	)
	chosen = next((r for r in rows if r.is_primary), rows[0] if rows else None)
	return f"{chosen.identifier_type}: {chosen.identifier_value}" if chosen else None


def refresh_search_index(patient: str) -> None:
	doc = frappe.get_doc("Patient", patient)
	set_search_index(doc)
	doc.db_set(SEARCH_FIELD, doc.get(SEARCH_FIELD), update_modified=False)


def is_identifier_unique_violation(exc: BaseException) -> bool:
	return UNIQUE_CONSTRAINT in str(exc)


def raise_friendly_unique_error(doc, exc: BaseException) -> None:
	"""Turn the DB unique-index error (race between two saves) into the FR-2 message."""
	for row in doc.get(PATIENT_IDENTIFIERS_FIELD) or []:
		owner = find_identifier_owner(row.identifier_type, row.normalised_value, exclude=doc.name)
		if owner:
			frappe.clear_last_message()
			frappe.throw(
				duplicate_message(row.identifier_type, row.identifier_value, owner),
				exc=DuplicateIdentifierError,
				title=_("Identifier Already Registered"),
			)
	frappe.clear_last_message()
	frappe.throw(
		_(
			"One of these identifiers was registered to another patient a moment ago. Search for it and open "
			"that record instead of registering the patient again (FR-2)."
		),
		exc=DuplicateIdentifierError,
		title=_("Identifier Already Registered"),
	)
