	def make_run(self, report: str, period=MAR, facility: int = 0) -> str:
		"""Create and generate a run as the HIS Officer. Returns its name."""
		with as_user(self.b.users["his"]):
			doc = frappe.get_doc(
				{
					"doctype": MOH_RUN_DOCTYPE,
					"report": report,
					"facility": self.facilities[facility],
					"period_type": "Monthly",
					"from_date": period[0],
					"to_date": period[1],
				}
			).insert()
			run_module.apply_action(doc.name, "generate")
		return doc.name

	def act(self, run: str, action: str, reason: str | None = None):
		with as_user(self.b.users["his"]):
			return run_module.apply_action(run, action, reason=reason)

	def cells(self, run: str) -> dict:
		snapshot = engine.snapshot_of(frappe.get_doc(MOH_RUN_DOCTYPE, run))
		return {k: v for k, v in engine.cells_of(snapshot).items() if v}

	def exceptions(self, run: str) -> list[tuple]:
		rows = frappe.get_all(
			"MOH Report Run Exception",
			filters={"parent": run, "parenttype": MOH_RUN_DOCTYPE},
			fields=["kind", "element", "reference_doctype", "reference_name", "detail"],
			order_by="idx asc",
		)
		return [
			(r.kind, r.element or None, r.reference_doctype or None, r.reference_name or None) for r in rows
		]

	def enc(self, key: str) -> str:
		return self.b.encounters[key]

