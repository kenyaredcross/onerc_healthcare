def with_totals(detail: dict, disaggregation: dict[str, str]) -> dict:
	"""Detail cells plus the documented engine totals: per disaggregated element its total, and for Age
	Band and Sex also each band's and each sex's total."""
	cells = dict(detail)
	for (code, band, sex), value in detail.items():
		kind = disaggregation.get(code)
		if not kind:
			continue
		cells[(code, "", "")] = cells.get((code, "", ""), 0) + value
		if kind == registry.DISAGGREGATION_AGE_SEX:
			cells[(code, band, "")] = cells.get((code, band, ""), 0) + value
			cells[(code, "", sex)] = cells.get((code, "", sex), 0) + value
	return {k: v for k, v in cells.items() if v}


def plain(expected: dict[str, int]) -> dict:
	return {(code, "", ""): v for code, v in expected.items() if v}


