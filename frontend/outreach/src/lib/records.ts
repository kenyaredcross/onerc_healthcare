export interface RecordContext {
  session: string;
  deviceId: string;
  now?: number;
}

export type FormErrors = Record<string, string>;

function compilePattern(pattern: string | null): RegExp | null {
  if (!pattern) return null;
  try {
    return new RegExp(pattern);
  } catch {
    return null;
  }
}

export function validateIdentifiers(ids: Identifier[], ref: Pick<ReferenceData, "identifier_types">): FormErrors {
  const errors: FormErrors = {};
  const seen = new Set<string>();
  ids.forEach((i, idx) => {
    const value = i.identifier_value.trim();
    if (!i.identifier_type && !value) return;
    const type = ref.identifier_types.find((t) => t.name === i.identifier_type);
    if (!type) errors[`identifier_${idx}`] = "Choose the identifier type.";
    else if (!value) errors[`identifier_${idx}`] = `Enter the ${type.name}.`;
    else if (type.facility_generated) errors[`identifier_${idx}`] = `${type.name} is generated by the facility.`;
    else {
      const re = compilePattern(type.pattern);
      if (re && !re.test(value)) errors[`identifier_${idx}`] = `${value} is not a valid ${type.name}.`;
    }
    const k = `${i.identifier_type}:${normaliseIdentifier(value)}`;
    if (seen.has(k)) errors[`identifier_${idx}`] = "This identifier is entered twice.";
    seen.add(k);
  });
  return errors;
}

export function validateRegister(form: RegisterForm, ref: Pick<ReferenceData, "identifier_types" | "genders">): FormErrors {
  const errors: FormErrors = { ...validateIdentifiers(form.identifiers, ref) };
  if (!form.first_name.trim()) errors.first_name = "Enter the first name.";
  if (!form.last_name?.trim()) errors.last_name = "Enter the last name.";
  if (!form.sex) errors.sex = "Choose the sex.";
  if (form.dob_mode === "exact") {
    if (!form.dob) errors.dob = "Enter the date of birth, or switch to an estimated age.";
    else if (form.dob > siteToday()) errors.dob = "The date of birth cannot be in the future.";
  } else {
    const y = Number(form.age_years || 0);
    const m = Number(form.age_months || 0);
    if (!Number.isInteger(y) || y < 0 || y > 120) errors.age_years = "Age in years must be 0-120.";
    if (!Number.isInteger(m) || m < 0 || m > 11) errors.age_months = "Months must be 0-11.";
    if (!errors.age_years && !errors.age_months && y === 0 && m === 0) errors.age_years = "Enter the estimated age.";
  }
  const primaryTypes = new Set(ref.identifier_types.filter((t) => t.is_primary).map((t) => t.name));
  const hasPrimary = form.identifiers.some((i) => primaryTypes.has(i.identifier_type) && i.identifier_value.trim());
  if (!hasPrimary && !form.is_walk_in) {
    errors.identifiers = "Add a primary identifier (e.g. UNHCR ID), or mark the patient as a walk-in.";
  }
  if (form.mobile && !/^[+0-9 ()-]{7,20}$/.test(form.mobile.trim())) errors.mobile = "Enter a valid phone number.";
  return errors;
}

/** DOB estimated from an age at `today` (same rule as registration/dob.py, for display only). */
export function estimateDob(today: string, years: number, months: number): string {
  const [y, m, d] = today.split("-").map(Number) as [number, number, number];
  const monthIndex = y * 12 + (m - 1) - (years * 12 + months);
  const ny = Math.floor(monthIndex / 12);
  const nm = monthIndex - ny * 12 + 1; // 1-based
  const lastDay = new Date(Date.UTC(ny, nm, 0)).getUTCDate();
  const day = Math.min(d, lastDay);
  return `${String(ny).padStart(4, "0")}-${String(nm).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
}

export async function registerPatient(keys: Keys, ctx: RecordContext, form: RegisterForm): Promise<LocalPatient> {
  const now = ctx.now ?? Date.now();
  const payload = buildPatientRegister(form);
  const env = buildEnvelope(RECORD_PATIENT_REGISTER, payload, {
    session: ctx.session,
    device_id: ctx.deviceId,
    captured_at: siteNow(now),
  });
  const key = await patientKey(keys, { name: null, client_uuid: env.client_uuid });
  const dob =
    payload.dob ??
    estimateDob(siteToday(now), payload.estimated_age_years ?? 0, payload.estimated_age_months ?? 0);
  const patient: LocalPatient = {
    key,
    name: null,
    client_uuid: env.client_uuid,
    modified: null,
    first_name: payload.first_name,
    middle_name: payload.middle_name,
    last_name: payload.last_name,
    sex: payload.sex,
    dob,
    dob_estimated: payload.dob ? 0 : 1,
    mobile: payload.mobile,
    residence: payload.residence,
    allergies: payload.allergies,
    is_walk_in: payload.is_walk_in,
    identifiers: payload.identifiers,
    recent_visits: [],
    active_prescriptions: [],
    outreach_visits: [],
    pending_updates: 0,
  };
  await putPatient(keys, patient);
  await addRecord(keys, env, `Registration: ${fullName(patient)}`, key, now);
  return patient;
}

/** Demographic edit of a package patient (patient.update with the package's `modified`). */
export async function updatePatient(
  keys: Keys,
  ctx: RecordContext,
  patient: LocalPatient,
  changes: PatientChanges,
  addIdentifiers: Identifier[],
): Promise<LocalPatient> {
  if (!patient.name || !patient.modified) {
    throw new Error("This patient was registered on this device; edit after the next package download.");
  }
  const now = ctx.now ?? Date.now();
  const payload = buildPatientUpdate(patient.name, patient.modified, changes, addIdentifiers);
  if (!Object.keys(payload.changes).length && !payload.add_identifiers.length) {
    throw new Error("Nothing was changed.");
  }
  const env = buildEnvelope(RECORD_PATIENT_UPDATE, payload, {
    session: ctx.session,
    device_id: ctx.deviceId,
    captured_at: siteNow(now),
  });
  const updated: LocalPatient = {
    ...patient,
    ...(Object.fromEntries(
      Object.entries(payload.changes).filter(([k]) => !k.startsWith("estimated_age")),
    ) as Partial<LocalPatient>),
    identifiers: [...patient.identifiers, ...payload.add_identifiers],
    pending_updates: patient.pending_updates + 1,
  };
  if (payload.changes.estimated_age_years !== undefined) {
    updated.dob = estimateDob(
      siteToday(now),
      Number(payload.changes.estimated_age_years ?? 0),
      Number(payload.changes.estimated_age_months ?? 0),
    );
    updated.dob_estimated = 1;
  } else if (payload.changes.dob) updated.dob_estimated = 0;
  await putPatient(keys, updated);
  await addRecord(keys, env, `Demographics: ${fullName(updated)}`, patient.key, now);
  return updated;
}

export async function finishVisit(
  keys: Keys,
  ctx: RecordContext,
  draft: VisitDraft,
  ref: LoadedReference,
): Promise<string> {
  const invalid = firstInvalidStep(draft, ref);
  if (invalid >= 0) throw new Error("Some steps still need attention.");
  const now = ctx.now ?? Date.now();
  const payload = buildVisitCapture(draft);
  const env = buildEnvelope(RECORD_VISIT_CAPTURE, payload, {
    session: ctx.session,
    device_id: ctx.deviceId,
    captured_at: draft.started_at,
    depends_on: payload.patient_ref ? [payload.patient_ref] : [],
  });
  await addRecord(keys, env, `Visit: ${draft.patient.display} (${draft.department})`, draft.patient.key, now);
  const patient = await getPatient(keys, draft.patient.key);
  if (patient) {
    patient.outreach_visits = [
      {
        client_uuid: env.client_uuid,
        date: draft.started_at.slice(0, 10),
        department: draft.department,
        diagnoses: draft.consultation.diagnoses.map((d) => ({
          code: d.code_value,
          title: d.title,
          case_type: d.case_type,
        })),
        prescriptions: draft.prescriptions.map((p) => p.label),
      },
      ...patient.outreach_visits,
    ];
    await putPatient(keys, patient);
  }
  await deleteDraft(draft.id);
  return env.client_uuid;
}

export function validateActivity(form: CommunityActivityForm, ref: Pick<ReferenceData, "community_activity_types">): FormErrors {
  const errors: FormErrors = {};
  if (!ref.community_activity_types.includes(form.activity_type)) errors.activity_type = "Choose the activity type.";
  if (!form.activity_date) errors.activity_date = "Enter the date.";
  else if (form.activity_date > siteToday()) errors.activity_date = "The date cannot be in the future.";
  for (const f of ["participants_male", "participants_female"] as const) {
    const v = form[f];
    if (v !== null && v !== undefined && v !== "" && !(Number.isInteger(Number(v)) && Number(v) >= 0)) {
      errors[f] = "Enter a whole number.";
    }
  }
  const total = Number(form.participants_male || 0) + Number(form.participants_female || 0);
  if (!errors.participants_male && !errors.participants_female && total <= 0) {
    errors.participants_male = "Enter the number of participants.";
  }
  return errors;
}

export async function recordActivity(keys: Keys, ctx: RecordContext, form: CommunityActivityForm): Promise<string> {
  const now = ctx.now ?? Date.now();
  const payload = buildCommunityActivity(form);
  const env = buildEnvelope(RECORD_COMMUNITY_ACTIVITY, payload, {
    session: ctx.session,
    device_id: ctx.deviceId,
    captured_at: siteNow(now),
  });
  await addRecord(keys, env, `${payload.activity_type}: ${payload.topic ?? payload.location ?? payload.activity_date}`, null, now);
  return env.client_uuid;
}
