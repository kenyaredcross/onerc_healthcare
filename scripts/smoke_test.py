	ap.add_argument("--facility-code", default="NTK")
	a = ap.parse_args()

	admin = Client(a.url, a.site)
	if not check("Administrator login", admin.login("Administrator", a.admin_password).ok):
		return 1

	tag = rand(4).lower()
